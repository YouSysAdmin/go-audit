// TypeName returns the record type name, UNKNOWN[n] when it is not known.
func TypeName(t uint16) string {
	if name, ok := typeNames[t]; ok {
		return name
	}

	return "UNKNOWN[" + strconv.Itoa(int(t)) + "]"
}
