//go:build ignore

// Generates tables.go from the golang.org/x/sys syscall number lists.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

// audit arch name -> x/sys GOARCH suffix
var arches = []struct{ name, goarch string }{
	{"x86_64", "amd64"},
	{"i386", "386"},
	{"aarch64", "arm64"},
	{"arm", "arm"},
}

var line = regexp.MustCompile(`^\s+SYS_(\w+)\s+=\s+(\d+)$`)

func main() {
	out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", "golang.org/x/sys").Output()
	if err != nil {
		log.Fatal(err)
	}

	dir := strings.TrimSpace(string(out))

	var b bytes.Buffer
	b.WriteString("// Code generated by gen.go from golang.org/x/sys. DO NOT EDIT.\n\npackage syscalls\n\n")
	b.WriteString("var tables = map[string]map[int]string{\n")

	for _, a := range arches {
		names, err := read(filepath.Join(dir, "unix", "zsysnum_linux_"+a.goarch+".go"))
		if err != nil {
			log.Fatal(err)
		}

		nrs := make([]int, 0, len(names))
		for nr := range names {
			nrs = append(nrs, nr)
		}
		slices.Sort(nrs)

		fmt.Fprintf(&b, "\t%q: {\n", a.name)
		for _, nr := range nrs {
			fmt.Fprintf(&b, "\t\t%d: %q,\n", nr, names[nr])
		}
		b.WriteString("\t},\n")
	}

	b.WriteString("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}

	if err := os.WriteFile("tables.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// read returns number -> lowercase name, the first name wins for a number.
func read(path string) (map[int]string, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()

	names := make(map[int]string)
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		m := line.FindStringSubmatch(sc.Text())
		if m == nil || strings.HasSuffix(m[1], "_MASK") {
			continue
		}

		nr, err := strconv.Atoi(m[2])
		if err != nil {
			return nil, err
		}

		if _, ok := names[nr]; !ok {
			names[nr] = strings.ToLower(m[1])
		}
	}

	return names, sc.Err()
}
